/**
 * Post-build step:
 *
 *  1. Copy the hand-authored JSX-namespace augmentation
 *     `scripts/jsx-runtime-aug.d.ts` into
 *     `dist/resources/ui5/community/jsx/runtime/jsx-runtime-aug.d.ts`.
 *     Explains why in `scripts/jsx-runtime-aug.d.ts`.
 *
 *  2. Emit `dist/index.d.ts`. `ui5-tooling-transpile` emits per-file
 *     `.d.ts` declarations for each `.ts`/`.tsx` source, but does
 *     *not* produce an aggregating entry file. `package.json`
 *     promises `"types": "dist/index.d.ts"`, so consumers need that
 *     file to exist for TypeScript to see any of our types.
 *
 * The generated `dist/index.d.ts` is a list of
 * `/// <reference path="…">` lines, one per `.d.ts` found under
 * `dist/resources/`. Test declarations under `dist/test-resources/`
 * are deliberately excluded — they are not public API and would
 * otherwise leak the QUnit suite's types into every consumer.
 */
import { readdirSync, statSync, writeFileSync, existsSync, copyFileSync, mkdirSync } from "node:fs";
import { relative, join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = dirname(here);
const distDir = join(packageRoot, "dist");
const augSrc = join(here, "jsx-runtime-aug.d.ts");
const augDst = join(distDir, "resources/ui5/community/jsx/runtime/jsx-runtime-aug.d.ts");

// --- Step 1: copy the augmentation ------------------------------------------

if (!existsSync(augSrc)) {
	throw new Error(`build-index-dts: missing ${augSrc}`);
}
mkdirSync(dirname(augDst), { recursive: true });
copyFileSync(augSrc, augDst);

// --- Step 2: emit dist/index.d.ts -------------------------------------------

/** Recursively collect every `.d.ts` file under `root`. */
function collectDts(root) {
	const out = [];
	if (!existsSync(root)) return out;
	const stack = [root];
	while (stack.length > 0) {
		const dir = stack.pop();
		for (const entry of readdirSync(dir)) {
			const full = join(dir, entry);
			if (statSync(full).isDirectory()) {
				stack.push(full);
			} else if (entry.endsWith(".d.ts")) {
				out.push(full);
			}
		}
	}
	return out.sort();
}

// Only `dist/resources/` — the public API. `dist/test-resources/`
// (the QUnit suite) is intentionally omitted so consumers don't
// inherit test-only declarations through the package's `types` entry.
const files = collectDts(join(distDir, "resources"));

const lines = files.map(
	(file) => `/// <reference path="./${relative(distDir, file).split(/[\\/]/).join("/")}"/>`
);

const header =
	"// Generated by scripts/build-index-dts.mjs. DO NOT EDIT.\n" +
	"// Aggregates every .d.ts emitted by ui5-tooling-transpile (plus\n" +
	"// the hand-authored JSX-namespace augmentation from\n" +
	"// scripts/jsx-runtime-aug.d.ts) so TypeScript consumers can rely\n" +
	"// on the package's `types` entry (dist/index.d.ts) to see the\n" +
	"// full API surface.\n";

writeFileSync(join(distDir, "index.d.ts"), header + lines.join("\n") + "\n");

// eslint-disable-next-line no-console
console.log(`build-index-dts: copied augmentation + wrote dist/index.d.ts (${lines.length} references).`);
